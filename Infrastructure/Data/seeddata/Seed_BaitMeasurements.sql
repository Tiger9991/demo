SELECT
    CAST(t.[TrapNumber] AS INT)   AS [رقم_المصيدة],
    t.[TrapGroup]                  AS [المجموعة],
    t.[IndicatorStatus]            AS [الحالة_اللونية],
    t.[status]                     AS [حالة_الاتصال],
    COUNT(bm.[Id])                 AS [إجمالي_قياسات_الطعم],
    SUM(CASE WHEN bm.[CaptureEventId] IS NOT NULL THEN 1 ELSE 0 END) AS [مرتبط_باصطياد],
    SUM(CASE WHEN bm.[CaptureEventId] IS NULL     THEN 1 ELSE 0 END) AS [دوري_مستقل],
    MIN(bm.[BaitWeightGrams])      AS [أقل_وزن_g],
    MAX(bm.[BaitWeightGrams])      AS [أعلى_وزن_g],
    CAST(AVG(bm.[BaitWeightGrams]) AS DECIMAL(5,1)) AS [متوسط_وزن_g]
FROM [Traps] t
LEFT JOIN [BaitMeasurements] bm ON bm.[TrapId] = t.[Id]
GROUP BY t.[TrapNumber], t.[TrapGroup], t.[IndicatorStatus], t.[status]
ORDER BY CAST(t.[TrapNumber] AS INT);
GO

